  static bool get isRtl => rtl.contains(lang);

  static final Map<String, Map<String, String>> _tables = {
    'ur': _ur,
  };

  static String t(String en) {
    if (lang == 'en') return en;
    return _tables[lang]?[en] ?? en;
  }
}

